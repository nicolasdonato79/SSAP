-- Cada repuesto queda ligado a una marca de vehículo (para filtrar bien cuando el vendedor es multimarca).
-- La asigna la app al importar (DetectorMarca): por el modelo/vehículo, por la marca escrita,
-- por la marca del vendedor si trabaja una sola, o por la descripción. Los ítems ya cargados
-- se completan solos al arrancar la app (AsignadorMarca).
ALTER TABLE item_stock ADD COLUMN marca_id INTEGER REFERENCES marca (id);
CREATE INDEX ix_item_stock_marca ON item_stock (marca_id);

-- Catálogo de modelos para reconocer la marca por el vehículo ("Ranger" → Ford).
-- Un mismo modelo puede estar en dos marcas (ej. Grand Vitara: Suzuki y Chevrolet en Venezuela).
