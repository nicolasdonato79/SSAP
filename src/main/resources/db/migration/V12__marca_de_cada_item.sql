    id       SERIAL PRIMARY KEY,
    marca_id INTEGER     NOT NULL REFERENCES marca (id),
    nombre   VARCHAR(60) NOT NULL,
    CONSTRAINT uq_modelo UNIQUE (marca_id, nombre)
);

