-- Ciudades y pueblos de cada estado, para elegir en la configuración y filtrar la búsqueda.
-- Base: capitales de los 335 municipios + ciudades principales (github.com/zokeber/venezuela-json),
-- depuradas a mano (duplicados, tildes, "Vargas" -> La Guaira). Si falta un pueblo, el usuario elige "Otra".
CREATE TABLE ciudad (
    id      SERIAL PRIMARY KEY,
    estado  VARCHAR(60) NOT NULL,
    nombre  VARCHAR(80) NOT NULL,
    CONSTRAINT uq_ciudad UNIQUE (estado, nombre)
);

-- La búsqueda filtra por ciudad del vendedor sin distinguir mayúsculas.
CREATE INDEX ix_usuario_estado_ciudad ON usuario (estado, lower(ciudad));

